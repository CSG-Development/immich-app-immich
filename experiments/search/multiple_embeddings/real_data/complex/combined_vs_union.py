import argparse
import json
from pathlib import Path


# ============================================================
# CONSTANTS
# ============================================================

DEFAULT_INPUT = "./voc_similarity/results.json"
DEFAULT_OUTPUT = "./voc_similarity/combined_vs_individual.json"


# ============================================================
# LOGGING
# ============================================================

def log(message):
    print(
        f"[INFO] {message}",
        flush=True,
    )


# ============================================================
# LOAD
# ============================================================

def load_results(path):
    path = Path(path)

    if not path.exists():
        raise RuntimeError(
            f"Results file does not exist: {path}"
        )

    with path.open(
        "r",
        encoding="utf-8",
    ) as f:
        return json.load(f)


# ============================================================
# COMBINED QUERY
# ============================================================

def split_combined_query(query):
    """
    Convert:

        "aeroplane and person"

    into:

        ["aeroplane", "person"]

    The queries generated by the main script use " and "
    as the separator.
    """

    return [
        item.strip()
        for item in query.split(" and ")
        if item.strip()
    ]


# ============================================================
# INDIVIDUAL QUERY NAMES
# ============================================================

def resolve_individual_query_names(
    class_names,
    individual_results,
):
    """
    Resolve the individual queries participating in a
    combined query.

    Normally a combined query looks like:

        "bottle and person"

    and resolves to:

        ["bottle", "person"]

    Sometimes a combined query contains a comma-separated
    group:

        "bottle, chair, diningtable and person"

    If the exact key "bottle, chair, diningtable" does not
    exist in individual_results, it is expanded into:

        ["bottle", "chair", "diningtable", "person"]

    If an exact key does exist, it is kept as a single
    individual query.
    """

    resolved = []

    for class_name in class_names:

        # ----------------------------------------------------
        # Prefer an exact individual query if it exists.
        # ----------------------------------------------------

        if class_name in individual_results:
            if class_name not in resolved:
                resolved.append(class_name)

            continue

        # ----------------------------------------------------
        # Otherwise expand comma-separated class names.
        # ----------------------------------------------------

        parts = [
            item.strip()
            for item in class_name.split(",")
            if item.strip()
        ]

        for part in parts:

            if part in individual_results:
                if part not in resolved:
                    resolved.append(part)

    return resolved


# ============================================================
# BOOLEAN UNION
# ============================================================

def union_boolean(values):
    return any(values)


# ============================================================
# COPY RESULT
# ============================================================

def copy_result(values):
    """
    Keep only the fields needed by the comparison/viewer.

    This creates an independent object so that the original
    results.json structure is not modified.
    """

    return {
        "original": values["original"],

        "squared": values["squared"],

        "segmented_original": (
            values["segmented_original"]
        ),

        "segmented_squared": (
            values["segmented_squared"]
        ),

        "found": values["found"],

        "better": values["better"],

        "max_cosine": (
            values["max_cosine"]
        ),

        "max_modified_similarity": (
            values["max_modified_similarity"]
        ),
    }


# ============================================================
# INDIVIDUAL UNION
# ============================================================

def build_individual_union(
    individual_results,
    class_names,
):
    """
    Combine individual query results.

    Boolean fields are combined using OR.

    Numeric similarity fields use MAX.

    class_names must already contain the resolved individual
    query names.
    """

    selected = []

    for class_name in class_names:

        values = individual_results.get(
            class_name
        )

        if values is None:
            continue

        selected.append(
            values
        )

    if not selected:
        return None

    return {
        "queries": class_names,

        "original": union_boolean(
            value["original"]
            for value in selected
        ),

        "squared": union_boolean(
            value["squared"]
            for value in selected
        ),

        "segmented_original": union_boolean(
            value["segmented_original"]
            for value in selected
        ),

        "segmented_squared": union_boolean(
            value["segmented_squared"]
            for value in selected
        ),

        "found": union_boolean(
            value["found"]
            for value in selected
        ),

        "better": union_boolean(
            value["better"]
            for value in selected
        ),

        "max_cosine": max(
            value["max_cosine"]
            for value in selected
        ),

        "max_modified_similarity": max(
            value["max_modified_similarity"]
            for value in selected
        ),
    }


# ============================================================
# DIFFERENCES
# ============================================================

def compare_values(
    combined,
    individual_union,
):
    """
    Calculate the difference between the combined query
    and the union of individual queries.
    """

    return {
        "max_cosine_difference": (
            combined["max_cosine"]
            - individual_union["max_cosine"]
        ),

        "max_modified_similarity_difference": (
            combined["max_modified_similarity"]
            - individual_union[
                "max_modified_similarity"
            ]
        ),

        "original_difference": (
            combined["original"]
            != individual_union["original"]
        ),

        "squared_difference": (
            combined["squared"]
            != individual_union["squared"]
        ),

        "segmented_original_difference": (
            combined["segmented_original"]
            != individual_union[
                "segmented_original"
            ]
        ),

        "segmented_squared_difference": (
            combined["segmented_squared"]
            != individual_union[
                "segmented_squared"
            ]
        ),

        "found_difference": (
            combined["found"]
            != individual_union["found"]
        ),

        "better_difference": (
            combined["better"]
            != individual_union["better"]
        ),
    }


# ============================================================
# PROCESS ONE IMAGE
# ============================================================

def process_image(image_result):

    individual_results = image_result[
        "groups"
    ][
        "individual"
    ]

    combined_results = image_result[
        "groups"
    ][
        "combined"
    ]

    comparisons = {}

    for combined_query, combined_values in (
        combined_results.items()
    ):

        # ----------------------------------------------------
        # First split by "and".
        # ----------------------------------------------------

        class_names = split_combined_query(
            combined_query
        )

        # ----------------------------------------------------
        # Then resolve comma-separated groups against the
        # actual individual query results.
        #
        # Example:
        #
        #   ["bottle, chair, diningtable", "person"]
        #
        # becomes:
        #
        #   ["bottle", "chair", "diningtable", "person"]
        #
        # when those individual queries exist.
        # ----------------------------------------------------

        individual_class_names = (
            resolve_individual_query_names(
                class_names=class_names,
                individual_results=individual_results,
            )
        )

        individual_union = build_individual_union(
            individual_results=individual_results,
            class_names=individual_class_names,
        )

        if individual_union is None:
            continue

        differences = compare_values(
            combined=combined_values,
            individual_union=individual_union,
        )

        # ----------------------------------------------------
        # Keep the individual result for EVERY individual
        # query participating in the union.
        # ----------------------------------------------------

        individual_query_results = {}

        for class_name in individual_class_names:

            values = individual_results.get(
                class_name
            )

            if values is None:
                continue

            individual_query_results[
                class_name
            ] = copy_result(
                values
            )

        comparisons[
            combined_query
        ] = {
            "classes": individual_class_names,

            "combined": {
                "original": (
                    combined_values[
                        "original"
                    ]
                ),

                "squared": (
                    combined_values[
                        "squared"
                    ]
                ),

                "segmented_original": (
                    combined_values[
                        "segmented_original"
                    ]
                ),

                "segmented_squared": (
                    combined_values[
                        "segmented_squared"
                    ]
                ),

                "found": (
                    combined_values[
                        "found"
                    ]
                ),

                "better": (
                    combined_values[
                        "better"
                    ]
                ),

                "max_cosine": (
                    combined_values[
                        "max_cosine"
                    ]
                ),

                "max_modified_similarity": (
                    combined_values[
                        "max_modified_similarity"
                    ]
                ),
            },

            "individual_results": (
                individual_query_results
            ),

            "individual_union": (
                individual_union
            ),

            "difference": differences,
        }

    return comparisons


# ============================================================
# STATISTICS
# ============================================================

def create_statistics():
    return {
        "queries": 0,

        "found": {
            "same": 0,
            "different": 0,

            "combined_only": 0,
            "individual_union_only": 0,
        },

        "original": {
            "same": 0,
            "different": 0,
        },

        "squared": {
            "same": 0,
            "different": 0,
        },

        "segmented_original": {
            "same": 0,
            "different": 0,
        },

        "segmented_squared": {
            "same": 0,
            "different": 0,
        },

        "better": {
            "same": 0,
            "different": 0,
        },

        "max_cosine_difference": [],

        "max_modified_similarity_difference": [],

        "combined_higher_modified": 0,
        "individual_higher_modified": 0,
        "same_modified": 0,
    }


def update_statistics(
    statistics,
    comparison,
):
    combined = comparison[
        "combined"
    ]

    individual_union = comparison[
        "individual_union"
    ]

    difference = comparison[
        "difference"
    ]

    statistics[
        "queries"
    ] += 1

    # --------------------------------------------------------
    # Boolean fields
    # --------------------------------------------------------

    boolean_fields = [
        "original",
        "squared",
        "segmented_original",
        "segmented_squared",
        "found",
        "better",
    ]

    for field in boolean_fields:

        stats = statistics[field]

        if (
            combined[field]
            == individual_union[field]
        ):
            stats["same"] += 1
        else:
            stats["different"] += 1

    # --------------------------------------------------------
    # Found direction
    # --------------------------------------------------------

    if (
        combined["found"]
        == individual_union["found"]
    ):

        statistics[
            "found"
        ][
            "same"
        ] += 0

    elif combined["found"]:

        statistics[
            "found"
        ][
            "combined_only"
        ] += 1

    else:

        statistics[
            "found"
        ][
            "individual_union_only"
        ] += 1

    # --------------------------------------------------------
    # Numeric differences
    # --------------------------------------------------------

    cosine_difference = difference[
        "max_cosine_difference"
    ]

    modified_difference = difference[
        "max_modified_similarity_difference"
    ]

    statistics[
        "max_cosine_difference"
    ].append(
        cosine_difference
    )

    statistics[
        "max_modified_similarity_difference"
    ].append(
        modified_difference
    )

    if modified_difference > 0:

        statistics[
            "combined_higher_modified"
        ] += 1

    elif modified_difference < 0:

        statistics[
            "individual_higher_modified"
        ] += 1

    else:

        statistics[
            "same_modified"
        ] += 1


def calculate_numeric_statistics(values):

    if not values:
        return {
            "mean": None,
            "median": None,
            "min": None,
            "max": None,
        }

    values = sorted(values)

    count = len(values)

    if count % 2 == 0:

        median = (
            values[count // 2 - 1]
            + values[count // 2]
        ) / 2.0

    else:

        median = values[
            count // 2
        ]

    return {
        "mean": sum(values) / count,
        "median": median,
        "min": min(values),
        "max": max(values),
    }


def finalize_statistics(statistics):

    statistics[
        "max_cosine_difference"
    ] = calculate_numeric_statistics(
        statistics[
            "max_cosine_difference"
        ]
    )

    statistics[
        "max_modified_similarity_difference"
    ] = calculate_numeric_statistics(
        statistics[
            "max_modified_similarity_difference"
        ]
    )

    return statistics


